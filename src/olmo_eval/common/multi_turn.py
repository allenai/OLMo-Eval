"""Requests and replies for scripted multi-turn conversations.

A task that writes every user turn in advance sends the first turn as the request
and the rest as follow-ups; the ``multi_turn_chat`` scaffold asks each one with the
model's own earlier replies in the conversation and records one entry per turn.
"""

from __future__ import annotations

from collections.abc import Sequence

from olmo_eval.common.types import (
    FOLLOW_UP_TURNS_KEY,
    TURNS_KEY,
    LMOutput,
    LMRequest,
    RequestType,
)


def scripted_chat_request(user_turns: Sequence[str]) -> LMRequest:
    """Build a chat request that asks ``user_turns`` one after another."""
    first, *follow_ups = user_turns
    return LMRequest(
        request_type=RequestType.CHAT,
        messages=({"role": "user", "content": first},),
        metadata={FOLLOW_UP_TURNS_KEY: [{"role": "user", "content": turn} for turn in follow_ups]},
    )


def turn_count(request: LMRequest) -> int:
    """Number of user turns a scripted request asks."""
    return 1 + len((request.metadata or {}).get(FOLLOW_UP_TURNS_KEY, ()))


def turn_replies(output: LMOutput) -> list[str] | None:
    """The model's reply to each turn it reached, or None if the output has no replies."""
    turns = (output.metadata or {}).get(TURNS_KEY)
    return None if turns is None else [turn["text"] for turn in turns]


def missing_replies_error(benchmark: str) -> ValueError:
    """The error for an output that was not generated by the ``multi_turn_chat`` scaffold."""
    return ValueError(
        f"A {benchmark} output has no per-turn replies. The task has to run under a harness "
        "with scaffold=multi_turn_chat, for example `--harness multi_turn_chat`."
    )
