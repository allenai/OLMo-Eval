"""Generate src/olmo_eval_api/schemas/api.py from dashboard/contract/api-v1.schema.json.

The TypeScript contract is the source of truth; its JSON Schema is generated from it by the UI
tooling. This script turns that schema into Pydantic models so the read API's responses match
the contract field for field. Run it after changing api-types.ts:

    uv run python scripts/generate_api_schemas.py

tests/test_contract_api_models.py fails when the committed file is out of date.
"""

from __future__ import annotations

import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT.parent / "contract" / "api-v1.schema.json"
OUTPUT_PATH = ROOT / "src" / "olmo_eval_api" / "schemas" / "api.py"

# Scalar definitions emitted as type aliases instead of classes.
SCALAR_ALIASES = {
    "Integer": "int",
    "Count": "int",
    "TaskResultId": "int",
    "DateTime": "datetime",
    "DateString": "str",
    "JsonObject": "dict[str, Any]",
    "FlatMetrics": "dict[str, float | None]",
}
RESERVED = set(dir(BaseModel))

HEADER = '''"""Pydantic models for the dashboard read API (dashboard/contract/api-types.ts).

Generated by scripts/generate_api_schemas.py from dashboard/contract/api-v1.schema.json.
Do not edit by hand; change the contract and regenerate.
"""

# ruff: noqa: E501

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class _Response(BaseModel):
    model_config = ConfigDict(extra="forbid", protected_namespaces=(), populate_by_name=True)


class _Request(BaseModel):
    model_config = ConfigDict(extra="ignore", protected_namespaces=(), populate_by_name=True)

'''


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_\W]+", name) if part)


class Generator:
    def __init__(self, schema: dict[str, Any]) -> None:
        self.defs: dict[str, Any] = schema["definitions"]
        self.classes: dict[str, str] = {}
        self.order: list[str] = []
        self.aliases: dict[str, str] = {}
        self.visiting: set[str] = set()

    def is_request(self, name: str) -> bool:
        return name.endswith("Request") or name in {"DistributionKey", "CompareRequestBase"}

    def ref_type(self, ref: str) -> str:
        name = ref.rsplit("/", 1)[-1]
        if name in SCALAR_ALIASES:
            return SCALAR_ALIASES[name]
        definition = self.defs[name]
        if definition.get("type") == "object" or "properties" in definition:
            self.emit_class(name, definition)
            return name
        self.emit_alias(name, definition)
        return name

    def emit_alias(self, name: str, definition: dict[str, Any]) -> None:
        if name in self.aliases:
            return
        self.aliases[name] = self.type_of(definition, name)

    def type_of(self, prop: dict[str, Any], context: str) -> str:
        if "$ref" in prop:
            return self.ref_type(prop["$ref"])
        if "anyOf" in prop:
            parts = [self.type_of(p, context) for p in prop["anyOf"]]
            return " | ".join(dict.fromkeys(parts))
        if "const" in prop:
            return f"Literal[{prop['const']!r}]"
        if "enum" in prop:
            values = [v for v in prop["enum"] if v is not None]
            literal = f"Literal[{', '.join(repr(v) for v in values)}]"
            return f"{literal} | None" if None in prop["enum"] else literal
        types = prop.get("type")
        if isinstance(types, list):
            parts = [self.type_of({**prop, "type": t}, context) for t in types]
            return " | ".join(dict.fromkeys(parts))
        if types == "null":
            return "None"
        if types == "string":
            if prop.get("pattern"):
                return f"Annotated[str, Field(pattern={prop['pattern']!r})]"
            if prop.get("format") == "date-time":
                return "datetime"
            return "str"
        if types == "integer":
            return "int"
        if types == "number":
            return "float"
        if types == "boolean":
            return "bool"
        if types == "array":
            items = prop.get("items", {})
            if (
                items.get("type") == "array"
                and items.get("minItems") == 2
                and items.get("maxItems") == 2
            ):
                inner = self.type_of(items["items"], context)
                return f"list[tuple[{inner}, {inner}]]"
            return f"list[{self.type_of(items, context + 'Item')}]"
        if types == "object":
            if "properties" in prop:
                self.emit_class(context, prop)
                return context
            extra = prop.get("additionalProperties")
            if isinstance(extra, dict):
                return f"dict[str, {self.type_of(extra, context + 'Value')}]"
            return "dict[str, Any]"
        return "Any"

    def emit_class(self, name: str, definition: dict[str, Any]) -> None:
        if name in self.classes or name in self.visiting:
            return
        self.visiting.add(name)
        base = "_Request" if self.is_request(name) else "_Response"
        required = set(definition.get("required", []))
        lines = [f"class {name}({base}):"]
        if definition.get("description"):
            doc = definition["description"].replace('"""', "'''")
            lines.append(f'    """{doc}"""')
            lines.append("")
        props = definition.get("properties", {})
        if not props:
            lines.append("    pass")
        for prop_name, prop in props.items():
            py_type = self.type_of(prop, name + pascal(prop_name))
            field_args = []
            attr = prop_name
            if prop_name in RESERVED or keyword.iskeyword(prop_name):
                attr = prop_name + "_"
                field_args.append(f"alias={prop_name!r}")
            constraints = []
            if prop.get("type") == "array":
                if "minItems" in prop:
                    constraints.append(f"min_length={prop['minItems']}")
                if "maxItems" in prop:
                    constraints.append(f"max_length={prop['maxItems']}")
            if prop.get("type") == "string":
                if "minLength" in prop:
                    constraints.append(f"min_length={prop['minLength']}")
                if "maxLength" in prop:
                    constraints.append(f"max_length={prop['maxLength']}")
            field_args.extend(constraints)
            if prop_name not in required:
                if "None" not in py_type.split(" | "):
                    py_type = f"{py_type} | None"
                field_args.insert(0, "default=None")
            if field_args:
                lines.append(f"    {attr}: {py_type} = Field({', '.join(field_args)})")
            else:
                lines.append(f"    {attr}: {py_type}")
        self.visiting.discard(name)
        self.classes[name] = "\n".join(lines)
        self.order.append(name)

    def render(self) -> str:
        for name, definition in self.defs.items():
            if name in SCALAR_ALIASES:
                continue
            if definition.get("type") == "object" or "properties" in definition:
                self.emit_class(name, definition)
            else:
                self.emit_alias(name, definition)
        out = [HEADER]
        for alias, py_type in sorted(self.aliases.items()):
            out.append(f"{alias} = {py_type}")
        out.append("")
        for name in self.order:
            out.append("")
            out.append(self.classes[name])
            out.append("")
        out.append("")
        out.append("for _name, _model in list(globals().items()):")
        out.append(
            "    if _name[:1].isupper() and isinstance(_model, type)"
            " and issubclass(_model, BaseModel) and _model is not BaseModel:"
        )
        out.append("        _model.model_rebuild()")
        return "\n".join(out) + "\n"


def generate() -> str:
    schema = json.loads(SCHEMA_PATH.read_text())
    return Generator(schema).render()


def main() -> int:
    import subprocess

    OUTPUT_PATH.write_text(generate())
    subprocess.run(["ruff", "format", str(OUTPUT_PATH)], check=True, capture_output=True)
    print(f"wrote {OUTPUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
